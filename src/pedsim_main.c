/*
 * pedsim_main.c - Single-population backwards pedigree simulator
 *
 * Simulates the pedigree of n sampled individuals k generations back in a
 * Wright-Fisher population of N/2 males and N/2 females. Uses the
 * pedsim_multipop engine with one population and writes the pedigree in
 * the three-column pedtrans format.
 *
 * Copyright (C) 2025 Bruce Rannala
 * GNU Affero General Public License v3
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <math.h>
#include "pedsim_multipop.h"

static void print_usage(const char* progname) {
    fprintf(stderr, "Usage: %s [options]\n", progname);
    fprintf(stderr, "\nBackwards pedigree simulation in a single Wright-Fisher population\n\n");
    fprintf(stderr, "Options:\n");
    fprintf(stderr, "  -n NUM    Sample size (individuals at generation 0, default: 10)\n");
    fprintf(stderr, "  -N NUM    Population size, must be even (default: 1000)\n");
    fprintf(stderr, "  -k NUM    Generations to simulate backwards (default: 5)\n");
    fprintf(stderr, "  -s NUM    Random seed (default: 0 = time-based)\n");
    fprintf(stderr, "  -o FILE   Output pedigree file (default: stdout)\n");
    fprintf(stderr, "  -d FILE   Also write the pedigree in DOT format\n");
    fprintf(stderr, "  -S        Print the number of ancestors per generation to stderr\n");
    fprintf(stderr, "  -E        With -S, also print the approximate expected numbers\n");
    fprintf(stderr, "  -v        Verbose output\n");
    fprintf(stderr, "  -h        Show this help message\n");
    fprintf(stderr, "\nOutput format (founders first):\n");
    fprintf(stderr, "  individual father mother     (founders have father = mother = 0)\n");
    fprintf(stderr, "  Sampled individuals are named S<i>, ancestors I<i>.\n");
    fprintf(stderr, "\nExample:\n");
    fprintf(stderr, "  %s -n 20 -N 500 -k 10 -o pedigree.txt -d pedigree.dot -S\n", progname);
}

static void write_name(multipop_pedigree* ped, int id, FILE* out) {
    if (ped->individuals[id].generation == 0)
        fprintf(out, "S%d", id);
    else
        fprintf(out, "I%d", id);
}

/* Write pedigree in topological order: generation k (founders) down to 0 */
static void write_pedigree(multipop_pedigree* ped, FILE* out) {
    fprintf(out, "# Pedigree generated by pedsim: N=%d, n=%d, k=%d, seed=%lu\n",
            ped->populations[0].pop_size, ped->populations[0].sample_size,
            ped->k_generations, ped->seed);
    for (int t = ped->k_generations; t >= 0; t--) {
        multipop_generation* gen = ped->gens_by_pop[t]->generations[0];
        for (int s = 0; s < 2; s++) {
            int n = (s == 0) ? gen->n_males : gen->n_females;
            int* ids = (s == 0) ? gen->male_ids : gen->female_ids;
            for (int i = 0; i < n; i++) {
                multipop_indiv* indiv = &ped->individuals[ids[i]];
                write_name(ped, ids[i], out);
                if (indiv->is_founder) {
                    fprintf(out, " 0 0\n");
                } else {
                    fputc(' ', out);
                    write_name(ped, indiv->father_id, out);
                    fputc(' ', out);
                    write_name(ped, indiv->mother_id, out);
                    fputc('\n', out);
                }
            }
        }
    }
}

static void write_dot(multipop_pedigree* ped, FILE* out) {
    fprintf(out, "digraph pedigree {\n");
    fprintf(out, "  rankdir=TB;\n");
    for (int t = ped->k_generations; t >= 0; t--) {
        multipop_generation* gen = ped->gens_by_pop[t]->generations[0];
        fprintf(out, "  { rank=same;");
        for (int s = 0; s < 2; s++) {
            int n = (s == 0) ? gen->n_males : gen->n_females;
            int* ids = (s == 0) ? gen->male_ids : gen->female_ids;
            for (int i = 0; i < n; i++) {
                fputc(' ', out);
                write_name(ped, ids[i], out);
                fputc(';', out);
            }
        }
        fprintf(out, " }\n");
    }
    for (int i = 0; i < ped->n_individuals; i++) {
        multipop_indiv* indiv = &ped->individuals[i];
        fprintf(out, "  ");
        write_name(ped, i, out);
        fprintf(out, " [shape=%s];\n", indiv->sex == 0 ? "box" : "ellipse");
        if (indiv->is_founder) continue;
        int parents[2] = { indiv->father_id, indiv->mother_id };
        for (int p = 0; p < 2; p++) {
            fprintf(out, "  ");
            write_name(ped, parents[p], out);
            fprintf(out, " -> ");
            write_name(ped, i, out);
            fprintf(out, ";\n");
        }
    }
    fprintf(out, "}\n");
}

/*
 * Ancestors per generation. The expectation uses the recursion
 *   E[n_t] = 2M (1 - (1 - 1/M)^E[n_{t-1}]),  M = N/2,
 * since each of n_{t-1} individuals picks a father among M males and a
 * mother among M females. Plugging in the expectation of n_{t-1} makes it
 * an approximation (exact for t = 1).
 */
static void write_generation_stats(multipop_pedigree* ped, int expected, FILE* out) {
    double M = ped->populations[0].pop_size / 2.0;
    double e = ped->populations[0].sample_size;
    fprintf(out, "# gen  males  females  total%s\n", expected ? "   expected" : "");
    for (int t = 0; t <= ped->k_generations; t++) {
        multipop_generation* gen = ped->gens_by_pop[t]->generations[0];
        if (t > 0) e = 2.0 * M * (1.0 - pow(1.0 - 1.0 / M, e));
        fprintf(out, "  %3d  %5d  %7d  %5d", t, gen->n_males, gen->n_females,
                gen->n_males + gen->n_females);
        if (expected) fprintf(out, "  %9.2f", e);
        fprintf(out, "\n");
    }
}

int main(int argc, char** argv) {
    int sample_size = 10;
    int pop_size = 1000;
    int k_generations = 5;
    unsigned long seed = 0;
    char* output_file = NULL;
    char* dot_file = NULL;
    int stats = 0;
    int expected = 0;
    int verbose = 0;

    int c;
    while ((c = getopt(argc, argv, "n:N:k:s:o:d:SEvh")) != -1) {
        switch (c) {
            case 'n': sample_size = atoi(optarg); break;
            case 'N': pop_size = atoi(optarg); break;
            case 'k': k_generations = atoi(optarg); break;
            case 's': seed = strtoul(optarg, NULL, 10); break;
            case 'o': output_file = optarg; break;
            case 'd': dot_file = optarg; break;
            case 'S': stats = 1; break;
            case 'E': expected = 1; break;
            case 'v': verbose = 1; break;
            case 'h':
                print_usage(argv[0]);
                return 0;
            default:
                print_usage(argv[0]);
                return 1;
        }
    }
    if (expected) stats = 1;

    multipop_pop_params params = { 0, pop_size, sample_size };
    multipop_pedigree* ped = multipop_create(&params, 1, NULL, k_generations, seed);
    if (!ped) return 1;

    if (multipop_simulate(ped) < 0) {
        fprintf(stderr, "Error: simulation failed\n");
        multipop_free(ped);
        return 1;
    }

    if (verbose) {
        fprintf(stderr, "pedsim: N=%d n=%d k=%d seed=%lu\n",
                pop_size, sample_size, k_generations, ped->seed);
        fprintf(stderr, "Total individuals: %d\n", ped->n_individuals);
    }
    if (stats) write_generation_stats(ped, expected, stderr);

    FILE* out = stdout;
    if (output_file) {
        out = fopen(output_file, "w");
        if (!out) {
            fprintf(stderr, "Error: cannot open output file: %s\n", output_file);
            multipop_free(ped);
            return 1;
        }
    }
    write_pedigree(ped, out);
    if (output_file) fclose(out);

    if (dot_file) {
        FILE* df = fopen(dot_file, "w");
        if (!df) {
            fprintf(stderr, "Error: cannot open DOT file: %s\n", dot_file);
            multipop_free(ped);
            return 1;
        }
        write_dot(ped, df);
        fclose(df);
    }

    multipop_free(ped);
    return 0;
}
